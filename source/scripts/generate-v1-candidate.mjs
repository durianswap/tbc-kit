import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "release/tws-v1-candidate.json");
const generatedReleasePath = path.join(
  root,
  "packages/core/src/generated/v1-candidate-release.ts",
);
const check = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new TypeError("generate-v1-candidate only accepts --check");
}

async function assets(directory) {
  const names = (await readdir(path.join(root, directory)))
    .filter((name) => name.endsWith(".json"))
    .sort();
  return Promise.all(names.map(async (name) => {
    const relative = `${directory}/${name}`;
    const bytes = await readFile(path.join(root, relative));
    JSON.parse(bytes.toString("utf8"));
    return Object.freeze({
      path: relative,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    });
  }));
}

function bundle(entries) {
  const bytes = entries.map(({ path: assetPath, sha256 }) =>
    `${assetPath}:${sha256}\n`).join("");
  return createHash("sha256").update(bytes).digest("hex");
}

function canonicalize(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalize).join(",")}]`;
  return `{${Object.keys(value).sort().map((key) =>
    `${JSON.stringify(key)}:${canonicalize(value[key])}`).join(",")}}`;
}

const schemaFiles = await assets("schemas");
const registryFiles = await assets("registry");
const candidate = {
  format: "tws-v1-candidate-manifest",
  candidateVersion: "1.0.0-candidate.3",
  status: "pre-release",
  compatibilityBaseline: "legacy-window-turing-only",
  providerMethodCount: 22,
  providerEventCount: 6,
  schemaBundleSha256: bundle(schemaFiles),
  registryBundleSha256: bundle(registryFiles),
  schemaFiles,
  registryFiles,
};
const source = `${JSON.stringify(candidate, null, 2)}\n`;
const releaseIdentity = {
  version: candidate.candidateVersion,
  schemaBundleSha256: candidate.schemaBundleSha256,
  registryBundleSha256: candidate.registryBundleSha256,
};
const releaseFingerprint = createHash("sha256")
  .update(canonicalize(releaseIdentity))
  .digest("hex");
const generatedRelease = `/* Generated by scripts/generate-v1-candidate.mjs. */

export const GENERATED_TWS_RELEASE = ${JSON.stringify(releaseIdentity, null, 2)} as const;

export const GENERATED_TWS_RELEASE_FINGERPRINT =
  ${JSON.stringify(releaseFingerprint)} as const;
`;

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => undefined);
  const currentRelease = await readFile(generatedReleasePath, "utf8").catch(
    () => undefined,
  );
  if (current !== source || currentRelease !== generatedRelease) {
    process.stderr.write(
      "TWS v1 candidate manifest is stale; run npm run generate:v1-candidate\n",
    );
    process.exitCode = 1;
  }
} else {
  await Promise.all([
    writeFile(outputPath, source, "utf8"),
    writeFile(generatedReleasePath, generatedRelease, "utf8"),
  ]);
}
