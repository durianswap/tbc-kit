import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compactValidatorSchemas } from "./lib/compact-validator-schemas.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaRoot = path.join(root, "schemas");
const releasePath = path.join(
  root,
  "release/tws-v1-candidate.json",
);
const outputPath = path.join(
  root,
  "packages/provider/src/generated/validators.ts",
);
const outputDirectory = path.join(
  root,
  "packages/provider/src/generated/validators",
);
const PROVIDER_SCHEMA_NAMES = Object.freeze([
  "common.schema.json",
  "integration.schema.json",
  "permissions.schema.json",
  "prepared-transaction.schema.json",
  "prepared-workflow.schema.json",
  "provider.schema.json",
  "reviewed-transaction.schema.json",
  "signing.schema.json",
  "transaction-request.schema.json",
  "workflow.schema.json",
  "wallet-actions.schema.json",
]);
const PROVIDER_REGISTRY_PATHS = new Set([
  "registry/errors.json",
  "registry/events.json",
  "registry/methods.json",
]);
const check = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new TypeError("generate-provider-validators only accepts --check");
}

const release = JSON.parse(await readFile(releasePath, "utf8"));
for (const entry of [
  ...release.schemaFiles.filter(({ path: file }) =>
    PROVIDER_SCHEMA_NAMES.includes(path.basename(file)),
  ),
  ...release.registryFiles.filter(({ path: file }) =>
    PROVIDER_REGISTRY_PATHS.has(file),
  ),
]) {
  const bytes = await readFile(path.join(root, entry.path));
  const actual = createHash("sha256").update(bytes).digest("hex");
  if (actual !== entry.sha256) {
    throw new Error(`Public integration candidate asset changed: ${entry.path}`);
  }
}

const schemaNames = PROVIDER_SCHEMA_NAMES;
const schemaEntries = await Promise.all(
  schemaNames.map(async (name) => [
    name,
    JSON.parse(await readFile(path.join(schemaRoot, name), "utf8")),
  ]),
);
const schemaIds = new Map(
  schemaEntries.map(([name, schema]) => [name, schema.$id]),
);

const methods = JSON.parse(
  await readFile(path.join(root, "registry/methods.json"), "utf8"),
).methods;
const events = JSON.parse(
  await readFile(path.join(root, "registry/events.json"), "utf8"),
).events;
const errors = JSON.parse(
  await readFile(path.join(root, "registry/errors.json"), "utf8"),
);

const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  validateFormats: true,
  inlineRefs: false,
  discriminator: true,
  code: { source: true, esm: true, lines: true, optimize: true },
});
ajv.addFormat("uri", /^[A-Za-z][A-Za-z0-9+.-]*:[^\s\u0000-\u001f\u007f]*$/);
ajv.addFormat("date-time", /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?Z$/);
for (const [, schema] of schemaEntries) ajv.addSchema(schema);

function schemaReference(reference) {
  const [schemaName, fragment = ""] = reference.split("#", 2);
  const schemaId = schemaIds.get(schemaName);
  if (!schemaId || !fragment.startsWith("/$defs/")) {
    throw new TypeError(`Unsupported Provider Schema reference: ${reference}`);
  }
  return `${schemaId}#${fragment}`;
}

const validatorReferences = {
  request: schemaReference("provider.schema.json#/$defs/request"),
  response: schemaReference("provider.schema.json#/$defs/response"),
  providerError: schemaReference("provider.schema.json#/$defs/providerError"),
  providerEvent: schemaReference("provider.schema.json#/$defs/providerEvent"),
  providerCompletion: schemaReference(
    "provider.schema.json#/$defs/providerCompletion",
  ),
};

for (const method of methods) {
  if (method.params.kind === "none") {
    if (method.params.schema !== undefined) {
      throw new TypeError(`${method.name} none params unexpectedly declare a Schema`);
    }
  } else {
    validatorReferences[`params_${method.name}`] = schemaReference(
      method.params.schema,
    );
  }
  validatorReferences[`result_${method.name}`] = schemaReference(
    method.result.schema,
  );
}
for (const event of events) {
  validatorReferences[`event_${event.name}`] = schemaReference(
    event.payload.schema,
  );
}
for (const [name, reference] of Object.entries(validatorReferences)) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
    throw new TypeError(`Generated validator export is not an identifier: ${name}`);
  }
  if (!ajv.getSchema(reference)) throw new Error(`${name} cannot resolve ${reference}`);
}

const executionStages = Object.fromEntries(
  errors.executionErrors.map(({ name, stages }) => [name, stages]),
);
const banner = `// @ts-nocheck
// Generated by scripts/generate-provider-validators.mjs from the public integration candidate.
// Candidate: ${release.candidateVersion}
// Schema bundle: ${release.schemaBundleSha256}
// Registry bundle: ${release.registryBundleSha256}
`;
const bundleSchema = {
  $id: "urn:tws:provider-validator-bundle:public-integration",
  type: "object",
  additionalProperties: false,
  required: ["selector", "value"],
  properties: {
    selector: { type: "string" },
    value: true,
  },
  discriminator: { propertyName: "selector" },
  oneOf: Object.entries(validatorReferences).map(([name, reference]) => ({
    type: "object",
    required: ["selector", "value"],
    properties: {
      selector: { const: name },
      value: { $ref: reference },
    },
  })),
};
const validateBundle = ajv.compile(bundleSchema);
const generated = compactValidatorSchemas(standaloneCode(ajv, validateBundle));
if (generated.includes("new Function") || /eval\s*\(/.test(generated)) {
  throw new Error("Generated Provider validator bundle contains dynamic code execution");
}
const bundlePath = path.join(outputDirectory, "bundle.ts");
const bundleSource = `${banner}${generated.trim()}\n`;
const bindings = Object.keys(validatorReferences)
  .map((name) => `export const ${name} = bind(${JSON.stringify(name)});`)
  .join("\n");
const source = `${banner}import validateBundle from "./validators/bundle.js";\n\ntype GeneratedValidator = ((value: unknown) => boolean) & { readonly errors?: unknown };\n\nfunction bind(selector: string): GeneratedValidator {\n  const validate = ((value: unknown) => validateBundle({ selector, value })) as GeneratedValidator;\n  Object.defineProperty(validate, "errors", { get: () => validateBundle.errors });\n  return validate;\n}\n\n${bindings}\n\nexport const TWS_PROVIDER_EXECUTION_ERROR_STAGES = Object.freeze(${JSON.stringify(executionStages, null, 2)});\n`;

async function verify(pathname, expected) {
  const current = await readFile(pathname, "utf8").catch(() => undefined);
  return current === expected;
}

if (check) {
  const results = await Promise.all([
    verify(outputPath, source),
    verify(bundlePath, bundleSource),
  ]);
  if (results.includes(false)) {
    process.stderr.write(
      "generated Provider validators are stale; run npm run generate:provider-validators\n",
    );
    process.exitCode = 1;
  }
} else {
  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  await Promise.all([
    writeFile(outputPath, source, "utf8"),
    writeFile(bundlePath, bundleSource, "utf8"),
  ]);
}
