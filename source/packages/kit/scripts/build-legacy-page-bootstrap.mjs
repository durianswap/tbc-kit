import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const entry = path.join(packageRoot, "src/legacy-webview-page-runtime.ts");
const target = path.join(packageRoot, "src/legacy-webview-page-bootstrap.ts");
const check = process.argv.includes("--check");
const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  sourcemap: false,
  treeShaking: true,
});
assert.equal(result.outputFiles.length, 1);
const bundle = `${result.outputFiles[0].text.trim()}\ntrue;`;
for (const forbidden of [
  "@tbc-wallet/host",
  "@tbc-wallet/tbc-engine",
  "@tbc-wallet/wallet-standard",
  "SecureStore",
  ["private", "Key"].join(""),
  "nodeUrl",
  "registerTbcWallet",
  "eval(",
  "new Function",
]) {
  assert.equal(
    bundle.includes(forbidden),
    false,
    `forbidden Legacy page capability: ${forbidden}`,
  );
}
const generated =
  `// Generated by packages/kit/scripts/build-legacy-page-bootstrap.mjs. Do not edit.\n` +
  `export const TBC_KIT_LEGACY_PAGE_BOOTSTRAP_SCRIPT = ${JSON.stringify(bundle)} as const;\n`;
if (check) {
  assert.equal(
    await fs.readFile(target, "utf8"),
    generated,
    "Kit Legacy page bootstrap is stale",
  );
} else {
  await fs.writeFile(target, generated, "utf8");
}
console.log(
  `TBC_KIT_LEGACY_PAGE_BOOTSTRAP_PASS bytes=${Buffer.byteLength(bundle, "utf8")} mode=${check ? "check" : "write"}`,
);
