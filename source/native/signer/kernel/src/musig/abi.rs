//! Wallet-private ABI. Caller guarantees valid disjoint buffers of fixed sizes.
//! Untrusted pages must never receive this API, its memory or private handles.
use super::{Error, Group, Round, registry::Registry};
use std::sync::{Mutex, OnceLock};
use zeroize::Zeroize;
static REGISTRY: OnceLock<Mutex<Registry>> = OnceLock::new();
const BUFFER: usize = 8192;
fn registry() -> &'static Mutex<Registry> { REGISTRY.get_or_init(|| Mutex::new(Registry::default())) }
fn code(error: Error) -> i32 { match error {
    Error::InvalidGroup=>101,Error::BindingMismatch=>102,Error::InvalidSecret=>103,
    Error::InvalidNonce=>104,Error::InvalidSignature=>105,Error::Consumed=>106,
    Error::CryptoFailure=>107,Error::Expired=>108,Error::Capacity=>109,
} }
unsafe fn bytes<const N:usize>(p:*const u8)->[u8;N]{unsafe{*p.cast::<[u8;N]>()}}
fn cancel(handle:[u8;32]) { if let Ok(mut r)=registry().lock(){r.cancel(handle);} }
#[unsafe(no_mangle)] pub extern "C" fn tbc_signer_musig_version()->u32{1}
/// # Safety
/// keys points to count*33 public bytes; aggregate to 32 writable bytes.
/// Buffers must be valid and disjoint. No custody or registry access.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tbc_signer_musig_aggregate_key(keys:*const u8,count:usize,aggregate:*mut u8)->i32{
    if !aggregate.is_null(){unsafe{std::ptr::write_bytes(aggregate,0,32)}}
    if keys.is_null()||aggregate.is_null()||!(2..=32).contains(&count){return 100}
    let keys=unsafe{std::slice::from_raw_parts(keys.cast::<[u8;33]>(),count)};
    match Group::from_public_keys(keys){
        Ok(group)=>{unsafe{std::ptr::copy_nonoverlapping(group.aggregate_key().as_ptr(),aggregate,32)};0},
        Err(error)=>code(error),
    }
}
#[unsafe(no_mangle)] pub extern "C" fn tbc_signer_musig_buffer_new()->*mut u8{Box::into_raw(Box::new([0u8;BUFFER])).cast()}
/// # Safety
/// Pointer from musig_buffer_new, freed exactly once; never use digest allocator.
#[unsafe(no_mangle)] pub unsafe extern "C" fn tbc_signer_musig_buffer_free(p:*mut u8){
    if !p.is_null(){let mut b=unsafe{Box::from_raw(p.cast::<[u8;BUFFER]>())};b.as_mut().zeroize();}
}
/// # Safety
/// count*33 keys; aggregate/digest/binding/scalar/entropy/handle each32; nonce66.
/// All buffers valid and disjoint. Entropy is freshly generated by trusted OS.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tbc_signer_musig_begin(
    keys:*const u8,count:usize,aggregate:*const u8,digest:*const u8,binding:*const u8,
    scalar:*const u8,entropy:*mut u8,now:u64,expires:u64,handle:*mut u8,nonce:*mut u8,
)->i32{
    if !handle.is_null(){unsafe{std::ptr::write_bytes(handle,0,32)}}
    if !nonce.is_null(){unsafe{std::ptr::write_bytes(nonce,0,66)}}
    if entropy.is_null(){return 100}
    let mut fresh=zeroize::Zeroizing::new(unsafe{bytes::<32>(entropy)});
    unsafe{std::slice::from_raw_parts_mut(entropy,32)}.zeroize();
    if keys.is_null()||aggregate.is_null()||digest.is_null()||binding.is_null()||scalar.is_null()||handle.is_null()||nonce.is_null()||!(2..=32).contains(&count){return 100}
    let result=(||{
        let keys=unsafe{std::slice::from_raw_parts(keys.cast::<[u8;33]>(),count)};
        let group=Group::new(keys,unsafe{bytes(aggregate)})?;
        registry().lock().map_err(|_|Error::CryptoFailure)?.begin(group,unsafe{bytes(digest)},unsafe{bytes(binding)},unsafe{&*scalar.cast::<[u8;32]>()},&mut fresh,now,expires)
    })();
    match result{Ok((h,n))=>{unsafe{std::ptr::copy_nonoverlapping(h.as_ptr(),handle,32);std::ptr::copy_nonoverlapping(n.as_ptr(),nonce,66)};0},Err(e)=>code(e)}
}
/// # Safety
/// handle/binding/digest/scalar/output32, nonces count*66; valid/disjoint buffers.
/// Invalid input consumes a recognizable handle; platform must recheck approval.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tbc_signer_musig_sign(handle:*const u8,binding:*const u8,digest:*const u8,scalar:*const u8,nonces:*const u8,count:usize,now:u64,output:*mut u8)->i32{
    if !output.is_null(){unsafe{std::ptr::write_bytes(output,0,32)}}
    if handle.is_null(){return 100}
    let h=unsafe{bytes(handle)};
    if binding.is_null()||digest.is_null()||scalar.is_null()||nonces.is_null()||output.is_null()||!(2..=32).contains(&count){cancel(h);return 100}
    let result=registry().lock().map_err(|_|Error::CryptoFailure).and_then(|mut r|r.sign_once(h,unsafe{bytes(binding)},unsafe{bytes(digest)},unsafe{&*scalar.cast::<[u8;32]>()},unsafe{std::slice::from_raw_parts(nonces.cast::<[u8;66]>(),count)},now));
    match result{Ok(sig)=>{unsafe{std::ptr::copy_nonoverlapping(sig.as_ptr(),output,32)};0},Err(e)=>code(e)}
}
/// # Safety
/// handle32 points to valid storage.
#[unsafe(no_mangle)] pub unsafe extern "C" fn tbc_signer_musig_cancel(handle:*const u8){if !handle.is_null(){cancel(unsafe{bytes(handle)})}}
#[unsafe(no_mangle)] pub extern "C" fn tbc_signer_musig_cancel_all(){if let Ok(mut r)=registry().lock(){r.cancel_all();}}
/// # Safety
/// keys count*33, aggregate/digest32, nonces count*66, shares count*32, output64.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tbc_signer_musig_combine(keys:*const u8,count:usize,aggregate:*const u8,digest:*const u8,nonces:*const u8,shares:*const u8,output:*mut u8)->i32{
    if !output.is_null(){unsafe{std::ptr::write_bytes(output,0,64)}}
    if keys.is_null()||aggregate.is_null()||digest.is_null()||nonces.is_null()||shares.is_null()||output.is_null()||!(2..=32).contains(&count){return 100}
    let result=(||{
        let group=Group::new(unsafe{std::slice::from_raw_parts(keys.cast::<[u8;33]>(),count)},unsafe{bytes(aggregate)})?;
        Round::new(group,unsafe{bytes(digest)},unsafe{std::slice::from_raw_parts(nonces.cast::<[u8;66]>(),count)})?.combine(unsafe{std::slice::from_raw_parts(shares.cast::<[u8;32]>(),count)})
    })();
    match result{Ok(sig)=>{unsafe{std::ptr::copy_nonoverlapping(sig.as_ptr(),output,64)};0},Err(e)=>code(e)}
}
